package Pojo_classes_automation_framework;

public class DashboardDetail {

	private String details_key;

	public DashboardDetail(String details_key) {
		super();
		this.details_key = details_key;
	}

	public DashboardDetail() {
		super();
	}

	public String getDetails_key() {
		return details_key;
	}

	public void setDetails_key(String details_key) {
		this.details_key = details_key;
	}
	
	
	
}
